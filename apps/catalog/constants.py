"""
Константы каталога: пороги оптовых цен и их отображаемые названия.

ВАЖНО про base_amount:
Порог проверяется по СУММЕ КОРЗИНЫ В РОЗНИЧНЫХ ЦЕНАХ, а не по итоговой.
Иначе получится бесконечный цикл: корзина перевалила 10 000 → применили
опт1 → сумма стала 9 500 → опт отменился → сумма снова 10 500 → ...
Использование base_amount делает результат детерминированным.
"""

from decimal import Decimal

# Минимальная сумма корзины (по розничным ценам) для применения тира.
# Список ОТСОРТИРОВАН по убыванию порога — это важно!
# Логика get_price_for_amount() идёт от старшего тира к младшему,
# поэтому первое совпадение = самая выгодная цена для клиента.
WHOLESALE_TIERS = [
    (Decimal("60000"), "price_opt3"),
    (Decimal("30000"), "price_opt2"),
    (Decimal("10000"), "price_opt1"),
]

# Полные названия тиров — для страницы товара, корзины, PDF-счёта.
TIER_LABELS = {
    "price_retail": "Розничная цена",
    "price_opt1": "Цена при заказе от 10 000 ₽",
    "price_opt2": "Цена при заказе от 30 000 ₽",
    "price_opt3": "Цена при заказе от 60 000 ₽",
}

# Короткие названия — для тесных мест: бейдж на карточке,
# плашка "применён опт 2", мобильная версия.
TIER_SHORT_LABELS = {
    "price_retail": "Розничная",
    "price_opt1": "Опт 1",
    "price_opt2": "Опт 2",
    "price_opt3": "Опт 3",
}

# Пороги в виде Decimal для UI: "до опта N осталось X ₽"
# Ключ — имя поля цены, значение — порог, при котором тир включается.
TIER_THRESHOLDS = {
    field_name: threshold
    for threshold, field_name in WHOLESALE_TIERS
}
